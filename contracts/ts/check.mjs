// Contract-lock check (TS half of `make contracts`). Run after contracts/tools/lock_check.py.
// Generates index.ts from schema/_all.json and validates every example with ajv,
// proving the Python and TS sides accept the same payloads.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020Module from "ajv/dist/2020.js";
import addFormatsModule from "ajv-formats";
import { compile } from "json-schema-to-typescript";

const Ajv2020 = Ajv2020Module.default ?? Ajv2020Module;
const addFormats = addFormatsModule.default ?? addFormatsModule;
const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "schema");
const examplesDir = join(here, "..", "examples");
const all = JSON.parse(readFileSync(join(schemaDir, "_all.json"), "utf8"));
const fixtures = JSON.parse(readFileSync(join(schemaDir, "_fixtures.json"), "utf8"));

const ts = await compile(all, "GhostBuildContracts", {
  bannerComment: "// GENERATED by `make contracts` from contracts/models.py. Do not edit.",
  unreachableDefinitions: true,
});
writeFileSync(join(here, "index.ts"), ts);

const ajv = new Ajv2020({ strict: false, allErrors: true });
addFormats(ajv);
ajv.addSchema(all, "all");

const glob = (p) => new RegExp("^" + p.replace(/[.+^${}()|\\]/g, "\\$&").replace(/\*/g, ".*").replace(/\?/g, ".") + "$");
let bad = 0;
let ok = 0;
for (const file of readdirSync(examplesDir).filter((f) => f.endsWith(".json")).sort()) {
  const hits = Object.keys(fixtures).filter((p) => glob(p).test(file));
  if (hits.length !== 1) {
    console.log(`RED  ${file}: matches ${hits.length} FIXTURES patterns`);
    bad++;
    continue;
  }
  const validate = ajv.compile({ $ref: "all" + fixtures[hits[0]] });
  if (validate(JSON.parse(readFileSync(join(examplesDir, file), "utf8")))) ok++;
  else {
    console.log(`RED  ${file}: ${ajv.errorsText(validate.errors)}`);
    bad++;
  }
}
if (bad) process.exit(1);
console.log(`GREEN ts: index.ts generated, ${ok} examples valid`);
