#!/usr/bin/env python3
"""Build G2-ready guide images + phone images + manifest from assets/sources/<guide_id>/.

    uv run python assets/build_guides.py                 # every guide dir
    uv run python assets/build_guides.py camera_lens     # one guide
    uv run python assets/build_guides.py --check         # build in memory, fail if committed outputs are stale

Outputs (knowledge/guides/<guide_id>/): <view>.png (G2, <=288x144, exactly the 16 gray4 levels),
<view>.phone.png (high-res, annotated), manifest.json. Also rewrites assets/INVENTORY.md.
Deterministic: same inputs -> byte-identical outputs (no timestamps).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "assets"))

from lib import gimage as gi  # noqa: E402

SOURCES = ROOT / "assets" / "sources"
OUT = ROOT / "knowledge" / "guides"
INVENTORY = ROOT / "assets" / "INVENTORY.md"


def build_guide(gdir: Path, out_root: Path, write: bool = True) -> tuple[dict, dict[str, bytes]]:
    """Return (manifest, {relative filename: bytes}). Raises GuideError; writes nothing unless `write`."""
    spec = gi.parse_guide(gdir / "annotations.json")
    files: dict[str, bytes] = {}
    views = []
    for v in spec.views:
        src_path = (gdir / v.source)
        src_bytes_hash = gi.sha256_hex(src_path.read_bytes()) if src_path.is_file() else None
        img = gi.load_source(src_path)
        g2 = gi.render_g2(img, v)
        levels = gi.grey_levels(g2)
        if len(levels) > gi.LEVELS or any(x % gi.STEP for x in levels) or g2.width > gi.G2_MAX_W or g2.height > gi.G2_MAX_H:
            raise gi.GuideError(f"internal: {spec.guide_id}/{v.view} violates the G2 image contract (levels={levels}, size={g2.size})")
        phone = gi.render_phone(img, v, placeholder=v.placeholder)
        g2_b, ph_b = gi.png_bytes(g2), gi.png_bytes(phone)
        files[f"{v.view}.png"], files[f"{v.view}.phone.png"] = g2_b, ph_b
        rel = f"knowledge/guides/{spec.guide_id}"
        views.append({
            "view": v.view, "step_id": v.step_id, "title": v.title,
            "image": f"{rel}/{v.view}.png", "phone_image": f"{rel}/{v.view}.phone.png",
            "provenance": v.provenance, "depicts": v.depicts, "fallback": v.fallback,
            "placeholder": v.placeholder, "fov_note": v.fov_note,
            "asset_kind": v.asset_kind, "reference_url": v.reference_url,
            "w": g2.width, "h": g2.height, "grey_levels": len(levels), "sha256": gi.sha256_hex(g2_b), "bytes": len(g2_b),
            "phone_w": phone.width, "phone_h": phone.height, "phone_sha256": gi.sha256_hex(ph_b), "phone_bytes": len(ph_b),
            "source": f"assets/sources/{spec.guide_id}/{v.source}", "source_sha256": src_bytes_hash,
            "annotation": v.annotation["type"], "caption": v.caption,
        })
    manifest = {
        "guide_id": spec.guide_id, "title": spec.title, "placeholder": spec.placeholder,
        "pipeline_version": gi.PIPELINE_VERSION,
        "g2_format": "PNG, 8-bit greyscale, values only multiples of 17 (= 16 gray4 levels), black = transparent, <=288x144",
        "views": views,
        # Paste-ready for card.guides[] (exactly contracts.models.Guide):
        "guide": {"id": spec.guide_id, "title": spec.title[:64], "views": [
            {"view": x["view"], "step_id": x["step_id"], "title": x["title"], "image": x["image"],
             "phone_image": x["phone_image"], "provenance": x["provenance"], "depicts": x["depicts"],
             "fallback": x["fallback"], "fov_note": x["fov_note"], "reference_url": x["reference_url"]} for x in views]},
    }
    files["manifest.json"] = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode()
    if write:
        gout = out_root / spec.guide_id
        gout.mkdir(parents=True, exist_ok=True)
        for name, data in files.items():
            (gout / name).write_bytes(data)
    return manifest, files


def inventory_md(manifests: list[dict], errors: dict[str, str]) -> str:
    rows = ["# Guide image inventory", "",
            "Generated by `assets/build_guides.py` (do not edit by hand). `PLACEHOLDER` = schematic stand-in, NOT a rig photo.", "",
            "| guide | view | step_id | file | provenance | placeholder? | status |", "|---|---|---|---|---|---|---|"]
    for m in manifests:
        for v in m["views"]:
            status = "PLACEHOLDER schematic - needs real photo" if v["placeholder"] else {
                "photograph": "built from photograph", "original_diagram": "original instructional diagram (not a photo)",
            }.get(v.get("asset_kind"), "source type unspecified (not verified as a photo)")
            rows.append(f"| {m['guide_id']} | {v['view']} | {v['step_id']} | `{v['image']}` ({v['w']}x{v['h']}, {v['bytes']} B) "
                        f"| {v['provenance']} | {'yes' if v['placeholder'] else 'no'} | {status} |")
    for gid, err in errors.items():
        rows.append(f"| {gid} | - | - | - | - | - | BUILD FAILED: {err.splitlines()[0][:90]} |")
    return "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("guides", nargs="*", help="guide ids (default: every folder in assets/sources)")
    ap.add_argument("--sources", type=Path, default=SOURCES)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--inventory", type=Path, default=INVENTORY)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if committed outputs differ")
    a = ap.parse_args(argv)

    ids = a.guides or sorted(p.name for p in a.sources.iterdir() if p.is_dir() and not p.name.startswith((".", "_")))
    if not ids:
        print(f"no guide folders in {a.sources}", file=sys.stderr)
        return 1
    manifests, errors, stale = [], {}, []
    for gid in ids:
        gdir = a.sources / gid
        try:
            if not gdir.is_dir():
                raise gi.GuideError(f"{gdir}: no such guide folder")
            m, files = build_guide(gdir, a.out, write=not a.check)
            manifests.append(m)
            if a.check:
                stale += [f"{gid}/{n}" for n, b in files.items() if not (a.out / gid / n).is_file() or (a.out / gid / n).read_bytes() != b]
            for v in m["views"]:
                print(f"  {gid}/{v['view']:<7} {v['w']}x{v['h']} {v['bytes']:>5} B  levels={v['grey_levels']:<2} {v['provenance']}"
                      f"{'  [PLACEHOLDER]' if v['placeholder'] else ''}")
        except gi.GuideError as e:
            errors[gid] = str(e)
            print(f"ERROR {gid}: {e}", file=sys.stderr)
    if not a.check:
        a.inventory.write_text(inventory_md(manifests, errors), encoding="utf-8")
    if a.check and stale:
        print("STALE outputs (run `make guides`): " + ", ".join(stale), file=sys.stderr)
    print(f"{len(manifests)} guide(s) built, {len(errors)} failed")
    return 1 if errors or stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
