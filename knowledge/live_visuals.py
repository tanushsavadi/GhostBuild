"""Pictures for a live-researched card: the research agent's own diagram (SVG) -> a 288x144 G2 image + a phone image.

Honesty: the diagram is generated by the agent (a drawing, never a photo and never a verification of the user's hardware); it is
labelled that way in every view's `depicts`. The outputs live under knowledge/live/ (gitignored), outside the committed
assets/ pipeline, and use the same renderer (assets/lib/gimage) so the G2 image contract (<=288x144, 16 grey levels) holds.
Best effort: any failure returns None and the card simply has no picture (text cues remain).
"""

from __future__ import annotations

import json
import logging
import re
import sys
from pathlib import Path
from typing import Any, Optional

log = logging.getLogger("ghostbuild.live_visuals")

REPO_ROOT = Path(__file__).resolve().parents[1]
LIVE_GUIDES = "knowledge/live/guides"
SRC_DIR = "knowledge/live/sources"
VERB = re.compile(r"\b(wire|connect|place|plug|assemble|install|mount|attach|insert|build|solder)\b", re.I)


def svg_to_png(svg_text: str, scale: float = 2.0) -> bytes:
    import pymupdf  # dependency group `knowledge`; imported lazily so core runs without it

    doc = pymupdf.open(stream=svg_text.encode("utf-8"), filetype="svg")
    pix = doc[0].get_pixmap(matrix=pymupdf.Matrix(scale, scale), alpha=False)
    return pix.tobytes("png")


def _guide_lib():
    sys.path.insert(0, str(REPO_ROOT / "assets"))
    import build_guides as bg  # noqa: WPS433  (script module; same renderer as `make guides`)

    return bg


def step_indexes_for_diagram(payload_steps: list[Any], card_steps: list[dict]) -> list[int]:
    """Which card steps get the picture. Steps whose own `visuals` mention a diagram/schematic/svg; else the first action step that
    wires/places/connects something; else the first step. Only when the payload and the card have the same steps in the same order."""
    hits: list[int] = []
    if len(payload_steps) == len(card_steps):
        for i, st in enumerate(payload_steps):
            blob = json.dumps(st.get("visuals") if isinstance(st, dict) else "", ensure_ascii=False).lower()
            if any(k in blob for k in (".svg", ".png", "schematic", "diagram")):
                hits.append(i)
    if hits:
        return hits[:4]
    for i, st in enumerate(card_steps):
        if VERB.search(st.get("title", "") + " " + st.get("detail", "")):
            return [i]
    return [0] if card_steps else []


def raster_to_png(data: bytes) -> bytes:
    """Validate a raster diagram (PNG/JPEG) and re-encode it as PNG; refuses anything that is not a sane image."""
    import io

    from PIL import Image

    im = Image.open(io.BytesIO(data))
    im.load()
    if im.width < 64 or im.height < 64 or im.width * im.height > 16_000_000:
        raise ValueError("implausible image size")
    out = io.BytesIO()
    im.convert("RGB").save(out, "PNG")
    return out.getvalue()


def build_live_guide(root: Path, run_key: str, svg_text: Optional[str], provenance: str, source_url: Optional[str] = None,
                     png_bytes: Optional[bytes] = None) -> Optional[dict]:
    """Render the diagram (SVG text or PNG/JPEG bytes) and return a `Guide` dict for card.guides[] (one view, `correct` = how the
    finished work looks), or None."""
    try:
        png = raster_to_png(png_bytes) if png_bytes else svg_to_png(svg_text or "")
        gid = "live_" + re.sub(r"[^a-z0-9]", "", run_key.lower())[:10]
        src = root / SRC_DIR / gid
        src.mkdir(parents=True, exist_ok=True)
        (src / "diagram.src.png").write_bytes(png)
        from PIL import Image
        import io

        w, h = Image.open(io.BytesIO(png)).size
        inset = 0.03
        spec = {
            "guide_id": gid, "title": "DIAGRAM", "placeholder": False, "asset_kind": "ai_diagram", "units": "px",
            "views": [{
                "view": "correct", "step_id": f"{gid}.correct", "title": "DIAGRAM", "source": "diagram.src.png",
                "crop": [0, 0, w, h],
                "annotation": {"type": "rect", "x0": int(w * inset), "y0": int(h * inset), "x1": int(w * (1 - inset)), "y1": int(h * (1 - inset))},
                "caption": "AI DIAGRAM - SEE PHONE", "autocontrast": 0, "contrast": 1.15, "gamma": 1,
                "provenance": provenance,
                "fallback_cue": {"line1": "DIAGRAM ON YOUR PHONE", "line2": "TEXT STEPS STILL APPLY"},
                "depicts": "Diagram generated by the research agent from its sources. A drawing, not a photo of your hardware, and not human-reviewed.",
                **({"reference_url": source_url} if source_url else {}),
            }],
        }
        (src / "annotations.json").write_text(json.dumps(spec, indent=2, ensure_ascii=False), encoding="utf-8")
        out = root / LIVE_GUIDES
        manifest, _ = _guide_lib().build_guide(src, out, write=True)
        guide = manifest["guide"]
        for v in guide["views"]:  # the shared builder names committed paths; these live elsewhere
            for k in ("image", "phone_image"):
                v[k] = v[k].replace("knowledge/guides/", LIVE_GUIDES + "/", 1)
        return guide
    except Exception:
        log.exception("could not build a picture from the research diagram")
        return None
